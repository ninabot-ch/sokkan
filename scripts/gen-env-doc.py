#!/usr/bin/env python3
"""Generate docs/ENVIRONMENT.md — the reference of every variable docker-compose.yml passes
to the api container: its default, the code that reads it, and what the compose file says.

    python3 scripts/gen-env-doc.py           write the file
    python3 scripts/gen-env-doc.py --check   exit 1 when the file on disk is stale (CI / tests)

The list is not written by hand: tests/test_compose_env.py fails when the backend reads a
variable that is not declared, and when this page is stale."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "ENVIRONMENT.md"
sys.path.insert(0, str(ROOT / "tests"))


def parse_api_block() -> list[dict]:
    """[{name, default, source, comment}] in file order (comment = the lines above the variable;
    a comment applies to the variables that follow it until a blank or another comment)."""
    lines = (ROOT / "docker-compose.yml").read_text().splitlines()
    start = next(i for i, x in enumerate(lines) if x.startswith("  api:"))
    env = next(i for i in range(start, len(lines)) if lines[i].strip() == "environment:")
    out, comment, fresh = [], [], False
    for raw in lines[env + 1:]:
        if raw.startswith("    ") and not raw.startswith("      "):
            break                                            # next key of the service
        s = raw.strip()
        if s.startswith("#"):
            if not fresh:
                comment = []
            comment.append(s.lstrip("# ").rstrip())
            fresh = True
            continue
        m = re.match(r"([A-Z][A-Z0-9_]*):\s*(.*)$", s)
        if not m:
            continue
        fresh = False
        name, val = m.group(1), m.group(2).split("  #")[0].strip()
        d = re.match(r'^"?\$\{([A-Z0-9_]+):-(.*)\}"?$', val)
        if d:
            source, default = d.group(1), d.group(2)
        else:
            source, default = "", val
        out.append({"name": name, "default": default, "source": source,
                    "comment": " ".join(comment)})
    return out


def render() -> str:
    import test_compose_env as guard
    reads = guard.env_reads()
    rows = parse_api_block()
    head = [
        "# Environment reference", "",
        "<!-- GENERATED by scripts/gen-env-doc.py — do not edit; run the script after changing "
        "docker-compose.yml -->", "",
        f"Every variable `docker-compose.yml` passes to the `api` container ({len(rows)}). Set them in "
        "`.env` (same folder as the compose file). A variable that is in `.env` but not in this list "
        "never reaches the container. Empty default = the default of the code. Feature switches "
        "(`SOKKAN_FEATURE_*`) are described one by one in [enterprise/FEATURES.md](enterprise/FEATURES.md); "
        "the on-prem appliance profile in [appliance/README.md](appliance/README.md).", "",
        "| Variable | Default | Read by | Notes (from docker-compose.yml) |", "|---|---|---|---|",
    ]
    body = []
    for r in rows:
        name = r["name"]
        files = set(reads.get(name, ()))
        for a, b in (("CORTHEXIS_", "SOKKAN_"), ("SOKKAN_", "CORTHEXIS_")):
            if name.startswith(a):
                files |= set(reads.get(b + name[len(a):], ()))
        if name in guard.PASSED_THROUGH and not files:
            files = {"Claude CLI" if name.startswith(("ANTHROPIC", "CLAUDE")) else "memory/core/models.py"}
        src = f" (`.env`: `{r['source']}`)" if r["source"] and r["source"] != name else ""
        default = f"`{r['default']}`" if r["default"] else "—"
        note = r["comment"].replace("|", "\\|")
        body.append(f"| `{name}`{src} | {default} | {', '.join(sorted(files)[:3]) or '—'} | {note} |")
    return "\n".join(head + body) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/ENVIRONMENT.md is stale: run python3 scripts/gen-env-doc.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
