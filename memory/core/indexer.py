CHUNK_TARGET = 1200     # chars; pack paragraphs up to this size
EMBED_BATCH = 64
INDEX_MAX_BYTES = 24_000  # the harness truncates MEMORY.md past ~24.4 KB…
INDEX_MAX_LINES = 190     # …and loads only its first 200 lines
RECENT_DAYS = 21
INDEX_HEADER = ("<!-- Generated by the memory indexer from the notes' descriptions — do not edit "
                "by hand. Overview only: read the notes with memory_search / memory_get. -->\n\n")


# ---------------------------------------------------------------- chunking

_SENTENCE_END = re.compile(r"(?<=[.!?…:;])[\"')\]»]*\s+(?=[\"'(«\[*_`#>-]?[A-Z0-9À-Ý])")


def _split_long(text: str, limit: int) -> list[str]:
    """Pieces of ``text`` of at most ``limit`` chars: lines, then sentences, then words."""
    if len(text) <= limit:
        return [text]
    lines = [ln for ln in text.split("\n") if ln.strip()]
    if len(lines) > 1:
        units = lines
        sep = "\n"
    else:
        units = [s for s in _SENTENCE_END.split(text) if s.strip()]
        sep = " "
        if len(units) <= 1:
            words, units, cur = text.split(), [], ""
            for w in words:
                while len(w) > limit:           # one unbreakable token (URL, base64…)
                    if cur:
                        units.append(cur)
                        cur = ""
                    units.append(w[:limit])
                    w = w[limit:]
                if cur and len(cur) + 1 + len(w) > limit:
                    units.append(cur)
                    cur = w
                else:
                    cur = f"{cur} {w}" if cur else w
            if cur:
                units.append(cur)
            return units
    out: list[str] = []
    for u in units:
        out.extend(_split_long(u.strip(), limit))
    return _pack(out, limit, sep)


def _pack(pieces: list[str], limit: int, sep: str) -> list[str]:
    chunks: list[str] = []
    cur = ""
    for p in pieces:
        if cur and len(cur) + len(sep) + len(p) > limit:
            chunks.append(cur)
            cur = p
        else:
            cur = f"{cur}{sep}{p}" if cur else p
    if cur:
        chunks.append(cur)
    return chunks


def chunk_body(body: str, target: int = CHUNK_TARGET) -> list[str]:
    """Chunks of at most ``target`` chars, cut on paragraphs, then lines, then
    sentences (a 2.x chunk could be any size: one long paragraph = one chunk)."""
    body = (body or "").strip()
    if not body:
        return []
    if len(body) <= target:
        return [body]
    pieces: list[str] = []
    for para in (p.strip() for p in re.split(r"\n\s*\n", body)):
        if para:
            pieces.extend(_split_long(para, target))
    return _pack(pieces, target, "\n\n")


def embed_text(name: str, description: str, chunk: str) -> str:
    """Name + description prepended to every chunk: keywords lift recall."""
    return f"{name}. {description}. {chunk}"


# ---------------------------------------------------------------- dead paths

def find_dead_paths(body: str, roots: list[Path], prefixes: tuple[str, ...]) -> list[str]:
    """Repository paths (``<prefix>/…``) quoted by a note that exist in none of ``roots``.

    Run where the indexer runs, against every repository the notes talk about: a
    reviewer that sees only one checkout reports paths of the others as dead.
    """
    if not roots or not prefixes:
        return []
    # not preceded by a word, a path separator or a dot: "/x/.openclaw/openclaw.json" is not
    # the repository path "openclaw/openclaw.json"
    rx = re.compile(r"(?<![\w/.~-])((?:" + "|".join(map(re.escape, prefixes)) + r")/[\w\-./]+)")
    gone = r"(removed|deleted|supprimés?|retirés?|n'existe plus|n'existe pas|décommissionnée?s?)"
    acked = re.compile(r"^[`'\"»\s]*\(" + gone, re.I)
    acked_line = re.compile(gone, re.I)
    found: set[str] = set()
    matches = list(rx.finditer(body))
    tails = []
    for i, m in enumerate(matches):
        # what the note says right after this path (up to the next path, same line)
        stop = min([x for x in (body.find("\n", m.end()), m.end() + 50,
                                matches[i + 1].start() if i + 1 < len(matches) else -1)
                    if x >= 0])
        tails.append(body[m.end():stop])
    connector = re.compile(r"^[`'\"\s,+&/]*(?:\b(?:et|and|ou|or)\b)?[`'\"\s,+&]*$", re.I)

    def gone_after(i: int) -> bool:
        """« `a` + `b` retirés » marks both; « a, b (removed) » marks only b."""
        while True:
            w = acked_line.search(tails[i])
            if w and "(" not in tails[i][:w.start()]:
                return True
            if i + 1 < len(matches) and connector.match(tails[i]):
                i += 1
                continue
            return False

    for i, m in enumerate(matches):
        nxt = body[m.end():m.end() + 60]
        if (nxt[:1] and nxt[:1] in "{*…") or acked.match(nxt) or gone_after(i):
            continue        # a glob, a range ("0001…0011"), or marked as gone in the note
        p = m.group(1).rstrip(".,;:)»'\"`")
        if any(ch in p for ch in "*{<>$…") or p.endswith("/") or p.endswith("-"):
            continue
        if p.count("/") == 1 and "." not in p.split("/")[-1]:
            continue        # "infra/TF", "docs/maic": a folder named in prose, not a file
        found.add(p)
    # A path is reported only when its folder still exists somewhere: the file moved or was
    # deleted next to its siblings. A path whose folder exists nowhere is, far more often, a
    # fragment of prose ("infra/TF"), a path of a repository that is not checked here, or
    # a truncated quote — 9 of the 12 remaining reports on a 415-note corpus (03.10.2026).
    return sorted(p for p in found
                  if not any((r / p).exists() for r in roots)
                  and any((r / p).parent.is_dir() for r in roots))


# ---------------------------------------------------------------- MEMORY.md

_RULE_PREAMBLE = re.compile(
    r"^(?:Rule|Règle|RÈGLE|Principle[^—:]{0,40}?|Principe[^—:]{0,40}?|Pitfall[^—:]{0,40}?|"
    r"Piège[^—:]{0,40}?)\b[^—:]{0,70}?\d{4}\)?[^—:]{0,60}?\s[—:]\s*")


def _hook(text: str) -> str:
    """The description without a "Rule born on <date> (context) —" preamble that would
    eat the whole truncated hook."""
    text = " ".join((text or "").split())
    stripped = _RULE_PREAMBLE.sub("", text, count=1)
    return (stripped[:1].upper() + stripped[1:]) if len(stripped) > 20 else text


def _truncate(text: str, cap: int) -> str:
    if len(text) <= cap:
        return text
    cut = text[: cap - 1]
    sp = cut.rfind(" ")
    if sp > cap // 2:
        cut = cut[:sp]
    return cut.rstrip(" ,;:—-") + "…"


def render_memory_index(
    notes: list[NoteRecord],
    *,
    now: datetime.datetime | None = None,
    max_lines: int = INDEX_MAX_LINES,
    max_bytes: int = INDEX_MAX_BYTES,
    recent_days: int = RECENT_DAYS,
    header: str | None = None,
) -> tuple[str, dict]:
    """MEMORY.md in three tiers, within ``max_lines`` AND ``max_bytes``:

    1. rules (``feedback`` / ``user`` notes) and ``priority`` notes, with their hook:
       they must be read without being searched for;
    2. notes updated in the last ``recent_days`` (effective date), most recent first;
    3. ALL notes grouped by family (first name segment), bare links: the overview
       is exhaustive, no note can drop out of the index silently.

    Past ~200 notes the line budget bites first: one line per note used to cut the
    end of the index without any signal. Levers, in order: recent hooks and count,
    then the length of rule hooks, then one-note families packed on shared lines.
    """
    now = now or dates.utcnow()
    rows = sorted(notes, key=lambda n: n.name.lower())
    header = header if header is not None else INDEX_HEADER
    cutoff = now - datetime.timedelta(days=recent_days)
    rules = [n for n in rows if n.type in ("feedback", "user") or n.priority]
    rule_names = {n.name for n in rules}
    dated = []
    for n in rows:
        if n.name in rule_names:
            continue
        mod = dates.parse_dt(n.modified)
        if mod and mod >= cutoff:
            dated.append((mod, n))
    dated.sort(key=lambda t: t[0], reverse=True)
    recent_all = [n for _m, n in dated]

    families: dict[str, list[NoteRecord]] = {}
    for n in rows:
        families.setdefault(n.name.split("-")[0], []).append(n)

    def link(n: NoteRecord) -> str:
        fname = Path(n.source_path).name
        return n.name if fname == filename_for(n.name) else f"[{n.name}]({fname})"

    family_lines = ["- **{}** — {}".format(fam, " · ".join(link(n) for n in group))
                    for fam, group in sorted(families.items())]
    # last lever: one-note families packed together on a few lines
    singles = [link(g[0]) for _f, g in sorted(families.items()) if len(g) == 1]
    packed = [f"- **{fam}** — {' · '.join(link(n) for n in group)}"
              for fam, group in sorted(families.items()) if len(group) > 1]
    cur = ""
    for s_ in singles:
        if cur and len(cur) + len(s_) > 600:
            packed.append("- " + cur)
            cur = s_
        else:
            cur = f"{cur} · {s_}" if cur else s_
    if cur:
        packed.append("- " + cur)

    hooks = {n.name: _hook(n.description) for n in rows}
    cache: dict[tuple[str, int], str] = {}

    def line(n: NoteRecord, cap: int) -> str:
        key = (n.name, cap)
        if key not in cache:
            star = "★ " if n.priority else ""
            desc = _truncate(hooks[n.name], cap)
            fname = Path(n.source_path).name
            cache[key] = (f"- {star}[{n.name}]({fname}) — {desc}" if desc
                          else f"- {star}[{n.name}]({fname})")
        return cache[key]

    def render(cap: int, n_recent: int, recent_cap: int, fam_lines: list[str]) -> str:
        recent = recent_all[:n_recent]
        title_recent = f"Updated in the last {recent_days} days ({len(recent)}"
        title_recent += (f" of {len(recent_all)}, most recent first)"
                         if len(recent) < len(recent_all) else ")")
        lines: list[str] = []
        if rules:
            lines.append(f"## Working rules ({len(rules)}) — apply them, do not search them\n")
            lines += [line(n, cap) for n in rules] + [""]
        if recent:
            lines.append(f"## {title_recent}\n")
            lines += [line(n, recent_cap) for n in recent] + [""]
        lines.append(f"## All notes by family ({len(rows)}) — file = name with \"_\"\n")
        lines += fam_lines
        return header + "\n".join(lines) + "\n"

    def fits(c: str) -> bool:
        return c.count("\n") <= max_lines and len(c.encode("utf-8")) <= max_bytes

    # largest number of recent notes that fits, by bisection (the size grows with it)
    ok = False
    content, n_kept = render(200, len(recent_all), 80, family_lines), len(recent_all)
    for fam_lines in (family_lines, packed):
        for cap in range(200, 39, -10):
            for rcap in (80, 50):
                if not fits(render(cap, 0, rcap, fam_lines)):
                    continue
                lo, hi = 0, len(recent_all)
                while lo < hi:
                    mid = (lo + hi + 1) // 2
                    if fits(render(cap, mid, rcap, fam_lines)):
                        lo = mid
                    else:
                        hi = mid - 1
                n_kept, content, ok = lo, render(cap, lo, rcap, fam_lines), True
                break
            if ok:
                break
        if ok:
            break
    stats = {"notes": len(rows), "families": len(families), "rules": len(rules),
             "recent": n_kept, "recent_total": len(recent_all), "lines": content.count("\n"),
             "bytes": len(content.encode("utf-8")), "fits": ok}
    return content, stats


